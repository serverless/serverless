// Command notices writes layer/sls-dev-THIRD_PARTY_NOTICES: the licence and notice files of Go
// and of every module linked into sls-dev-bridge (on linux/arm64 and linux/amd64), which the
// layer zip ships next to the binary (the sls-dev- prefix keeps it from clashing with other
// layers' files, as Lambda merges every layer into /opt). It reads them from the module cache
// and the Go installation. Run it from dev-mode-bridge after any change to go.mod:
//
//	go run ./cmd/notices -out layer/sls-dev-THIRD_PARTY_NOTICES
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// bridgePackage is the binary the layer ships.
const bridgePackage = "github.com/serverless/serverless/dev-mode-bridge/cmd/sls-dev-bridge"

const header = "Third-party software in the Serverless Framework Dev Mode bridge (bin/sls-dev-bridge).\n" +
	"Generated by `go run ./cmd/notices -out layer/sls-dev-THIRD_PARTY_NOTICES` in dev-mode-bridge; do not edit.\n"

// goSection heads Go's own licence: the standard library and runtime are linked into every Go
// binary. build-layer looks for the same line.
const goSection = "== Go standard library and runtime ==\n"

// licenceFiles are read from each module's directory, in this order, when present.
var licenceFiles = []string{"LICENSE", "LICENSE.txt", "LICENSE.md", "COPYING", "NOTICE", "NOTICE.txt", "NOTICE.md", "edl-v10"}

// chosen names the licence file that applies to a dual-licensed module; only that file is
// shipped, with a line saying which licence the Framework takes the module under.
var chosen = map[string]struct{ file, statement string }{
	"github.com/eclipse/paho.golang": {"edl-v10", "is used under the Eclipse Distribution License 1.0"},
}

// architectures are the GOARCH values the layer is built for.
var architectures = []string{"amd64", "arm64"}

type module struct{ path, version, dir string }

func main() {
	out := flag.String("out", "", "file to write")
	flag.Parse()
	if *out == "" {
		fmt.Fprintln(os.Stderr, "usage: notices -out <file>")
		os.Exit(2)
	}
	if err := run(*out, bridgePackage); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(out, pkg string) error {
	modules, err := linkedModules(pkg)
	if err != nil {
		return err
	}
	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return fmt.Errorf("go env GOROOT: %w", err)
	}
	var b strings.Builder
	b.WriteString(header)
	for _, m := range modules {
		if c, ok := chosen[m.path]; ok {
			fmt.Fprintf(&b, "%s %s.\n", m.path, c.statement)
		}
	}
	b.WriteString("\n" + goSection)
	if !writeLicences(&b, strings.TrimSpace(string(goroot)), []string{"LICENSE", "PATENTS"}) {
		return fmt.Errorf("no LICENSE in the Go installation at %s", strings.TrimSpace(string(goroot)))
	}
	for _, m := range modules {
		fmt.Fprintf(&b, "\n== %s %s ==\n", m.path, m.version)
		files := licenceFiles
		if c, ok := chosen[m.path]; ok {
			files = []string{c.file}
		}
		if !writeLicences(&b, m.dir, files) {
			return fmt.Errorf("%s %s has no licence file in %s", m.path, m.version, m.dir)
		}
	}
	return os.WriteFile(out, []byte(b.String()), 0o644)
}

// linkedModules lists the modules (other than this one) that provide a package pkg is built
// from, on every layer architecture, sorted by path.
func linkedModules(pkg string) ([]module, error) {
	seen := map[string]module{}
	for _, goarch := range architectures {
		cmd := exec.Command("go", "list", "-deps", "-f",
			"{{with .Module}}{{if not .Main}}{{with .Replace}}{{.Path}} {{.Version}} {{.Dir}}{{else}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}{{end}}", pkg)
		cmd.Env = append(os.Environ(), "CGO_ENABLED=0", "GOOS=linux", "GOARCH="+goarch)
		var stderr bytes.Buffer
		cmd.Stderr = &stderr
		listed, err := cmd.Output()
		if err != nil {
			return nil, fmt.Errorf("go list %s (linux/%s): %w: %s", pkg, goarch, err, stderr.String())
		}
		scanner := bufio.NewScanner(bytes.NewReader(listed))
		for scanner.Scan() {
			parts := strings.SplitN(scanner.Text(), " ", 3)
			if len(parts) == 3 {
				seen[parts[0]] = module{parts[0], parts[1], parts[2]}
			}
		}
	}
	modules := make([]module, 0, len(seen))
	for _, m := range seen {
		modules = append(modules, m)
	}
	sort.Slice(modules, func(i, j int) bool { return modules[i].path < modules[j].path })
	return modules, nil
}

// writeLicences appends each of names found in dir, with line endings normalised to LF, and
// reports whether any was found.
func writeLicences(b *strings.Builder, dir string, names []string) bool {
	found := false
	for _, name := range names {
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			continue
		}
		found = true
		text := strings.ReplaceAll(strings.ReplaceAll(string(data), "\r\n", "\n"), "\r", "\n")
		fmt.Fprintf(b, "-- %s --\n%s", name, text)
		if !strings.HasSuffix(text, "\n") {
			b.WriteString("\n")
		}
	}
	return found
}
