/** Logical ID of the execution role the Framework generates. */
export const DEFAULT_EXECUTION_ROLE_LOGICAL_ID = 'IamRoleLambdaExecution'

/**
 * How a compiled resource references its execution role, shared by functions
 * (`Role`) and web apps (`ExecutionRoleArn`): an ARN is used as is, a logical
 * role name or an `Fn::GetAtt` points at a role in the stack (which the
 * resource then depends on, unless it is the generated role), and any other
 * intrinsic (`Fn::ImportValue`, `Fn::Sub`, ...) passes through.
 *
 * @param {string|object} role - from `provider.getCustomExecutionRole`, or
 *   `IamRoleLambdaExecution` when that returns nothing
 * @returns {{ arn: string|object, dependsOn?: string }}
 */
export function resolveExecutionRoleRef(role) {
  if (typeof role === 'string') {
    // a statically defined IAM role ARN
    if (role.startsWith('arn:')) return { arn: role }
    const arn = { 'Fn::GetAtt': [role, 'Arn'] }
    // the default role generated by the framework
    if (role === DEFAULT_EXECUTION_ROLE_LOGICAL_ID) return { arn }
    // a logical role name
    return { arn, dependsOn: role }
  }
  // an "Fn::GetAtt" object
  if ('Fn::GetAtt' in role) {
    return { arn: role, dependsOn: role['Fn::GetAtt'][0] }
  }
  // an "Fn::ImportValue" or "Fn::Sub" object
  return { arn: role }
}
